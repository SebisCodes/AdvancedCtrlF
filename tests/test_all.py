from app import config as cfg  # noqa: E402
from app.extractors import Context, ExtractError, extract  # noqa: E402
from app.ocr import OcrEngine  # noqa: E402
from app.search import SearchIndex, format_location, target_of  # noqa: E402
import samples  # noqa: E402


class Base(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tmp = Path(tempfile.mkdtemp())
        cls.files = samples.make_all(cls.tmp / "in")
        # Redirect the document store into the temp folder so real data stays untouched
        cls._saved = (cfg.DOCS_DIR, cfg.INDEX_DIR)
        cfg.DOCS_DIR, cfg.INDEX_DIR = cls.tmp / "documents", cls.tmp / "index"
        cls.ocr = OcrEngine(cls.tmp / "tessdata", 300)
        cls.ctx = Context(dict(cfg.DEFAULTS), cls.ocr)

    @classmethod
    def tearDownClass(cls):
        cfg.DOCS_DIR, cfg.INDEX_DIR = cls._saved
        shutil.rmtree(cls.tmp, ignore_errors=True)

    def texts(self, name):
        res = extract(self.tmp / "in" / name, self.ctx)
        return res, "\n".join(c["text"] for c in res.chunks)


class ExtractTests(Base):
    def test_docx(self):
        res, text = self.texts("vertrag.docx")
        self.assertIn("Kündigungsfrist", text)
        self.assertIn("Organigramm der Abteilung", text)
        page2 = [c for c in res.chunks if "Probezeit" in c["text"]][0]
        self.assertEqual(page2["loc"]["page"], 2)
        caption = [c for c in res.chunks if "Abbildung 1" in c["text"]][0]
        self.assertEqual(caption["loc"]["part"], "Caption")
        self.assertIn("Fußzeile", text)
        self.assertIn("100 Euro", text)

    def test_pptx(self):
        res, _ = self.texts("bericht.pptx")
        by = {c["text"]: c["loc"] for c in res.chunks}
        cap = by["Abb. 3: Umsatz stieg um 12 Prozent"]
        self.assertEqual((cap["slide"], cap["part"]), (2, "Caption"))
        self.assertEqual(by["Diagramm Umsatzentwicklung"]["part"], "Image (alt text)")
        self.assertEqual(by["Sprechernotiz: Zahlen vorlesen"]["part"], "Notes")
        self.assertEqual(by["Fazit: Wachstum im Exportgeschäft"]["slide"], 2)
        self.assertEqual(res.meta["pages"], 2)

    def test_odt(self):
        _, text = self.texts("protokoll.odt")
        self.assertIn("Beschluss über das Budget", text)
        self.assertIn("Gruppenbild am See", text)

    def test_xlsx_cells(self):
        res, _ = self.texts("kunden.xlsx")
        row = [c for c in res.chunks if "Bäckerei" in c["text"]][0]
        off = row["text"].index("Stadt A")
        self.assertEqual(format_location(target_of(row["loc"], row["text"], off)), "Tabelle!B2")

    def test_pdf_text_and_ocr(self):
        res, text = self.texts("scan.pdf")
        self.assertIn("Kündigungsfrist", text)
        self.assertEqual([c for c in res.chunks if "warranty" in c["text"]][0]["loc"]["page"], 2)
        if self.ocr.available():
            self.assertEqual(res.meta["ocr_pages"], 2)
            self.assertIn("Rechnung", text)
            self.assertIn("invoice", text)
            self.assertEqual([c for c in res.chunks if "Rechnung" in c["text"]][0]["loc"]["page"], 3)
        else:
            print("\n  (no OCR language data available - OCR part skipped)")

    def test_html(self):
        _, text = self.texts("sloppy.html")
        self.assertIn("We are open on weekends", text)
        self.assertIn("Closed on public holidays", text)
        self.assertIn("Mon | 9-17", text)
        res, text = self.texts("app.html")
        for needle in ("Listing headline text", "Description generated by a script",
                       "Floor plan", "Remove page"):
            self.assertIn(needle, text)
        for junk in ("btnSave", "onclick", "class=", "pinRemove", "index identifiers"):
            self.assertNotIn(junk, text)
        line = [c for c in res.chunks if "Listing headline" in c["text"]][0]
        self.assertEqual(target_of(line["loc"], line["text"], line["text"].index("Listing headline"))["line"], 3)
        res, text = self.texts("seite.html")
        self.assertIn("Öffnungszeiten", text)
        self.assertIn("Logo oben links", text)
        self.assertNotIn("geheim", text)  # script content must be skipped
        ch = [c for c in res.chunks if "Öffnungszeiten" in c["text"]][0]
        self.assertEqual(target_of(ch["loc"], ch["text"], ch["text"].index("Öffnungszeiten"))["line"], 3)

    def test_misc_formats(self):
        for name, needle in [("liste.csv", "Dübel"), ("daten.xml", "Zeitüberschreitung"),
                             ("notiz.txt", "Passwortrichtlinien"), ("brief.rtf", "Grüße"),
                             ("mail.eml", "Angebot Migration")]:
            with self.subTest(name=name):
                self.assertIn(needle, self.texts(name)[1])

    def test_xml_entities_refused(self):
        with self.assertRaises(ExtractError):
            extract(self.tmp / "in" / "bomb.xml", self.ctx)


class ImageOcrTests(Base):
    """Every picture inside a document is OCR'd and attributed to its location."""

    def ocr_hits(self, name, needle):
        if not self.ocr.available():
            self.skipTest("no OCR language data available")
        res, _ = self.texts(name)
        return res, [c["loc"] for c in res.chunks if needle in c["text"]]

    def test_pdf_image_on_text_page(self):
        res, locs = self.ocr_hits("scan.pdf", "Warehouse inventory")
        self.assertEqual([(l["page"], l["part"]) for l in locs], [(2, "Image (OCR)")])
        self.assertIn("warranty period", "\n".join(c["text"] for c in res.chunks))  # text layer kept

    def test_docx_image(self):
        res, locs = self.ocr_hits("vertrag.docx", "Server room")
        self.assertEqual([(l["page"], l["part"]) for l in locs], [(2, "Image (OCR)")])
        self.assertEqual(res.meta["ocr_images"], 1)

    def test_pptx_image_deduplicated(self):
        res, locs = self.ocr_hits("bericht.pptx", "Revenue chart")
        self.assertEqual([(l["slide"], l["part"]) for l in locs], [(1, "Image (OCR)")])  # same picture on 2 slides

    def test_xlsx_image_anchor_cell(self):
        res, locs = self.ocr_hits("kunden.xlsx", "Signature field")
        self.assertEqual(len(locs), 1)
        self.assertEqual(format_location(target_of(locs[0], "", 0)), "Tabelle!D5 · Image (OCR)")

    def test_odt_image(self):
        _, locs = self.ocr_hits("protokoll.odt", "Whiteboard")
        self.assertEqual([(l["para"], l["part"]) for l in locs], [(4, "Image (OCR)")])

    def test_disabled(self):
        ctx = Context(dict(cfg.DEFAULTS, ocr_all_images=False), self.ocr)
        res = extract(self.tmp / "in" / "bericht.pptx", ctx)
        self.assertFalse(any("Revenue" in c["text"] for c in res.chunks))


class StoreAndSearchTests(Base):
    def test_store_archive_and_search(self):
        from app.store import Store
        store = Store(dict(cfg.DEFAULTS))
        docs = store.add_path(self.tmp / "in", self.ctx)
        names = {d.get("display_name") for d in docs}
        self.assertIn("in/archiv.zip › unterordner/innen.txt", names)
        self.assertFalse(any("evil" in (n or "") for n in names), "path traversal entry must be skipped")
        self.assertFalse((self.tmp / "evil.txt").exists())
        # Duplicates are detected by content hash
        again = store.add_path(self.files["docx"], self.ctx)
        self.assertTrue(again[0].get("duplicate"))
        # Reload from JSON and search
        ix = SearchIndex()
        for d in Store(dict(cfg.DEFAULTS)).load_all():
            ix.add(d)

        def top(q):
            hits, _ = ix.search(q)
            self.assertTrue(hits, q)
            h = hits[0]
            ch = ix.chunk_of(h)
            _, _, off = ix.snippet(h)
            return ix.docs[h.doc_id]["name"], format_location(target_of(ch["loc"], ch["text"], off))

        self.assertIn(top("Kündigungsfrist")[0], ("vertrag.docx", "scan.pdf"))
        self.assertEqual(top('"drei Monate"'), ("scan.pdf", "p. 1, l. 1"))
        self.assertEqual(top("Umsatzentwicklung"), ("bericht.pptx", "Slide 1 · Image (alt text)"))
        self.assertEqual(top("Revenue chart")[1], "Slide 1 · Image (OCR)")               # text inside a picture
        self.assertEqual(top("Gruppenbild"), ("protokoll.odt", "Paragraph 3 · Image (alt text)"))
        self.assertEqual(top("Archivinhalt")[0], "innen.txt")
        self.assertEqual(top("Baeckerei")[1], "Tabelle!A2")                 # umlaut folding
        self.assertEqual(top("Probezeit")[1], "p. ~2")                   # approximate Word page
        self.assertEqual(top("Probezeti")[1], "p. ~2")                   # typo tolerance
        self.assertEqual(top("warrenty")[0], "scan.pdf")                 # typo tolerance (English)
        self.assertEqual(top("vertrag type:docx")[0], "vertrag.docx")    # compound part + type filter
        self.assertEqual(top("vertrag typ:docx")[0], "vertrag.docx")     # German alias
        self.assertEqual(top("holidays file:sloppy")[0], "sloppy.html")  # file filter
        self.assertEqual(top("Passwort")[1], "Line 4")
        hits, _ = ix.search("Kündigungsfrist -Quartalsende")
        self.assertTrue(all(ix.docs[h.doc_id]["name"] != "scan.pdf" for h in hits))


