class ImageOcrTests(Base):
    """Every picture inside a document is OCR'd and attributed to its location."""

    def ocr_hits(self, name, needle):
        if not self.ocr.available():
            self.skipTest("no OCR language data available")
        res, _ = self.texts(name)
        return res, [c["loc"] for c in res.chunks if needle in c["text"]]

    def test_pdf_image_on_text_page(self):
        res, locs = self.ocr_hits("scan.pdf", "Warehouse inventory")
        self.assertEqual([(l["page"], l["part"]) for l in locs], [(2, "Image (OCR)")])
        self.assertIn("warranty period", "\n".join(c["text"] for c in res.chunks))  # text layer kept

    def test_docx_image(self):
        res, locs = self.ocr_hits("vertrag.docx", "Server room")
        self.assertEqual([(l["page"], l["part"]) for l in locs], [(2, "Image (OCR)")])
        self.assertEqual(res.meta["ocr_images"], 1)

    def test_pptx_image_deduplicated(self):
        res, locs = self.ocr_hits("bericht.pptx", "Revenue chart")
        self.assertEqual([(l["slide"], l["part"]) for l in locs], [(1, "Image (OCR)")])  # same picture on 2 slides

    def test_xlsx_image_anchor_cell(self):
        res, locs = self.ocr_hits("kunden.xlsx", "Signature field")
        self.assertEqual(len(locs), 1)
        self.assertEqual(format_location(target_of(locs[0], "", 0)), "Tabelle!D5 · Image (OCR)")

    def test_odt_image(self):
        _, locs = self.ocr_hits("protokoll.odt", "Whiteboard")
        self.assertEqual([(l["para"], l["part"]) for l in locs], [(4, "Image (OCR)")])

    def test_grayscale_image(self):
        import pymupdf
        from app.ocr import ImageOCR
        if not self.ocr.available():
            self.skipTest("no OCR language data available")
        gray = pymupdf.Pixmap(pymupdf.csGRAY, pymupdf.Pixmap(samples.text_png("Grayscale scan readable")))
        self.assertIn("Grayscale", ImageOCR(self.ctx).read("k", gray.tobytes("png")))

    def test_ocr_at_native_resolution(self):
        import pymupdf
        from app.ocr import native_dpi
        doc = pymupdf.open()
        page = doc.new_page(width=800, height=400)   # 1083 px wide image on 800 pt -> 97 dpi
        page.insert_image(page.rect, stream=samples.text_png("x"))
        self.assertEqual(native_dpi(page, 300), 97)
        self.assertEqual(native_dpi(doc.new_page(), 300), 300)  # no image: default

    def test_disabled(self):
        ctx = Context(dict(cfg.DEFAULTS, ocr_all_images=False), self.ocr)
        res = extract(self.tmp / "in" / "bericht.pptx", ctx)
        self.assertFalse(any("Revenue" in c["text"] for c in res.chunks))


class AnyFileAndRepositoryTests(Base):
    """Every file type is accepted; folders/archives behave like repositories."""

    def store(self):
        from app.store import Store
        cfg.DOCS_DIR, cfg.INDEX_DIR = self.tmp / f"docs{id(self)}", self.tmp / f"index{id(self)}"
        return Store(dict(cfg.DEFAULTS))

    def test_binary_file_found_by_name_and_strings(self):
        f = self.tmp / "firmware_update.bin"
        f.write_bytes(bytes(range(256)) * 50 + b"\x00Error: calibration sensor timeout\x00" + bytes(range(256)) * 50)
        doc = self.store().add_path(f, self.ctx)[0]
        self.assertEqual(doc["status"], "ok")
        self.assertIn("calibration sensor timeout", "\n".join(c["text"] for c in doc["chunks"]))
        ix = SearchIndex()
        ix.add(doc)
        self.assertTrue(ix.search("firmware")[0])            # by file name

    def test_file_without_text_still_searchable(self):
        f = self.tmp / "holiday_photo.raw"
        f.write_bytes(bytes(range(256)) * 400)
        doc = self.store().add_path(f, self.ctx)[0]
        self.assertEqual([c["loc"]["kind"] for c in doc["chunks"]], ["file"])
        ix = SearchIndex()
        ix.add(doc)
        hits, _ = ix.search("holiday photo")
        self.assertEqual(format_location(target_of(ix.chunk_of(hits[0])["loc"], "", 0)), "File name")

    def test_text_without_extension_and_notebook(self):
        (self.tmp / "Makefile").write_text("build:\n\tgcc -o tool main.c\n", encoding="utf-8")
        _, text = self.texts_at(self.tmp / "Makefile")
        self.assertIn("gcc -o tool", text)
        nb = {"cells": [{"cell_type": "markdown", "source": ["# Data cleaning"]},
                        {"cell_type": "code", "source": ["df = load()\n", "df.dropna()"],
                         "outputs": [{"output_type": "stream", "text": ["42 rows removed"]}]}]}
        (self.tmp / "analysis.ipynb").write_text(__import__("json").dumps(nb), encoding="utf-8")
        res, _ = self.texts_at(self.tmp / "analysis.ipynb")
        by = {c["text"]: c["loc"] for c in res.chunks}
        self.assertEqual(format_location(target_of(by["df = load()\ndf.dropna()"], "df = load()\ndf.dropna()", 13)),
                         "Cell 2, l. 2 · Code")
        self.assertEqual(by["42 rows removed"]["part"], "Output")

    def texts_at(self, path):
        res = extract(path, self.ctx)
        return res, "\n".join(c["text"] for c in res.chunks)

    def make_project(self, name):
        root = self.tmp / name
        for rel, text in {"src/app.py": "def checkout_cart(): pass", "README.md": "Project overview",
                          "node_modules/lib/index.js": "dependency code", ".venv/lib/x.py": "venv",
                          "build/secret.txt": "ignored by gitignore", ".gitignore": "build/\n"}.items():
            (root / rel).parent.mkdir(parents=True, exist_ok=True)
            (root / rel).write_text(text, encoding="utf-8")
        return root

    def test_folder_skips_dependency_and_cache_folders(self):
        root = self.make_project("plainproject")
        names = {d["display_name"] for d in self.store().add_path(root, self.ctx)}
        self.assertIn("plainproject/src/app.py", names)
        self.assertFalse(any("node_modules" in n or ".venv" in n for n in names), names)

    def test_git_repository_respects_gitignore(self):
        import shutil as sh
        import subprocess
        if not sh.which("git"):
            self.skipTest("git not installed")
        root = self.make_project("gitproject")
        subprocess.run(["git", "init", "-q", str(root)], check=True)
        names = {d["display_name"] for d in self.store().add_path(root, self.ctx)}
        self.assertIn("gitproject/src/app.py", names)
        self.assertNotIn("gitproject/build/secret.txt", names)            # .gitignore
        self.assertFalse(any("node_modules" in n for n in names))

    def test_repository_archive_with_subfolder(self):
        import zipfile
        z = self.tmp / "repo.zip"
        with zipfile.ZipFile(z, "w") as zf:      # GitHub layout: one top folder "<repo>-<branch>/"
            zf.writestr("shop-main/docs/guide.md", "Payment guide")
            zf.writestr("shop-main/src/cart.py", "def total(): pass")
            zf.writestr("shop-main/node_modules/x.js", "dependency")
        store = self.store()
        names = {d["display_name"] for d in store.add_repository_archive(z, "acme/shop", self.ctx, extra={"source": "s"})}
        self.assertEqual(names, {"acme/shop › docs/guide.md", "acme/shop › src/cart.py"})
        sub = store.add_repository_archive(z, "acme/shop@main", self.ctx, subpath="docs")
        self.assertEqual([d.get("display_name") or d.get("name") for d in sub], ["guide.md"])  # duplicate content

    def test_link_parsing(self):
        from app.remote import parse
        self.assertEqual(parse("https://github.com/acme/shop/tree/dev/docs/api")["path"], "docs/api")
        self.assertEqual(parse("https://github.com/acme/shop.git")["repo"], "shop")
        self.assertEqual(parse("https://example.org/a.pdf")["kind"], "file")
        with self.assertRaises(ExtractError):
            parse("http://example.org/a.pdf")


class StoreAndSearchTests(Base):
    def test_store_archive_and_search(self):
        from app.store import Store
        store = Store(dict(cfg.DEFAULTS))
        docs = store.add_path(self.tmp / "in", self.ctx)
        names = {d.get("display_name") for d in docs}
        self.assertIn("in/archiv.zip › unterordner/innen.txt", names)
        self.assertFalse(any("evil" in (n or "") for n in names), "path traversal entry must be skipped")
        self.assertFalse((self.tmp / "evil.txt").exists())
        # Duplicates are detected by content hash
        again = store.add_path(self.files["docx"], self.ctx)
        self.assertTrue(again[0].get("duplicate"))
        # Reload from JSON and search
        ix = SearchIndex()
        for d in Store(dict(cfg.DEFAULTS)).load_all():
            ix.add(d)

        def top(q):
            hits, _ = ix.search(q)
            self.assertTrue(hits, q)
            h = hits[0]
            ch = ix.chunk_of(h)
            _, _, off = ix.snippet(h)
            return ix.docs[h.doc_id]["name"], format_location(target_of(ch["loc"], ch["text"], off))

        self.assertIn(top("Kündigungsfrist")[0], ("vertrag.docx", "scan.pdf"))
        self.assertEqual(top('"drei Monate"'), ("scan.pdf", "p. 1, l. 1"))
        self.assertEqual(top("Umsatzentwicklung"), ("bericht.pptx", "Slide 1 · Image (alt text)"))
        self.assertEqual(top("Revenue chart")[1], "Slide 1 · Image (OCR)")               # text inside a picture
        self.assertEqual(top("Gruppenbild"), ("protokoll.odt", "Paragraph 3 · Image (alt text)"))
        self.assertEqual(top("Archivinhalt")[0], "innen.txt")
        self.assertEqual(top("Baeckerei")[1], "Tabelle!A2")                 # umlaut folding
        self.assertEqual(top("Probezeit")[1], "p. ~2")                   # approximate Word page
        self.assertEqual(top("Probezeti")[1], "p. ~2")                   # typo tolerance
        self.assertEqual(top("warrenty")[0], "scan.pdf")                 # typo tolerance (English)
        self.assertEqual(top("vertrag type:docx")[0], "vertrag.docx")    # compound part + type filter
        self.assertEqual(top("vertrag typ:docx")[0], "vertrag.docx")     # German alias
        self.assertEqual(top("holidays file:sloppy")[0], "sloppy.html")  # file filter
        self.assertEqual(top("Passwort")[1], "Line 4")
        hits, _ = ix.search("Kündigungsfrist -Quartalsende")
        self.assertTrue(all(ix.docs[h.doc_id]["name"] != "scan.pdf" for h in hits))


