"""Generate requirements.txt from requirements.in: exact versions, with the SHA-256 of every wheel.

    python -I tools/lock_deps.py

pip resolves requirements.in (newest versions allowed there, prebuilt wheels only, including
dependencies such as shiboken6 and et-xmlfile). For each resolved version the SHA-256 of all its
wheels is taken from PyPI, so the same file works on Windows, Linux and macOS. ensure_deps.py
installs it with pip --require-hashes: a file that is not byte-for-byte the locked one is refused.

The header line "# python-max: 3.X" is the newest Python series for which every package has
wheels on Windows (x64), Linux (x86-64) and macOS. The launchers and the Python updates never
install a newer Python than that.
Run this tool for every dependency update, test, and commit both files.
"""
import json
import re
import subprocess
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
IN = ROOT / "requirements.in"
OUT = ROOT / "requirements.txt"
# platforms a Python series must be covered on (wheel platform tag must contain one of these)
PLATFORMS = {"Windows": ("win_amd64",), "Linux": ("manylinux", "x86_64"), "macOS": ("macosx",)}


def pypi(name: str, version: str) -> dict:
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "AdvancedCtrlF"}),
                                timeout=60) as r:
        return json.load(r)


def resolve() -> list[tuple[str, str]]:
    out = subprocess.run([sys.executable, "-I", "-m", "pip", "install", "--dry-run", "--ignore-installed",
                          "--only-binary=:all:", "--quiet", "--disable-pip-version-check", "--report", "-",
                          "-r", str(IN)], check=True, capture_output=True, text=True).stdout
    items = json.loads(out)["install"]
    return sorted(((i["metadata"]["name"], i["metadata"]["version"]) for i in items), key=lambda x: x[0].lower())


def _platform_ok(tag: str, needs: tuple[str, ...]) -> bool:
    return tag == "any" or all(n in tag for n in needs)


def max_series(wheels: list[str]) -> int | None:
    """Newest minor version 3.X covered on all PLATFORMS by these wheel file names; None = any."""
    covered: dict[str, set[int] | None] = {}
    for plat, needs in PLATFORMS.items():
        minors: set[int] = set()
        for w in wheels:
            _, _, pyt, abi, platt = w[:-4].rsplit("-", 4)
            if not any(_platform_ok(p, needs) for p in platt.split(".")):
                continue
            if abi in ("none", "abi3"):                   # pure Python or stable ABI: open-ended
                minors = None
                break
            m = re.fullmatch(r"cp3(\d+)", abi)            # e.g. cp315 (not cp315t: free-threaded)
            if m:
                minors.add(int(m.group(1)))
        covered[plat] = minors
    limits = [max(m) for m in covered.values() if m is not None and m]
    if any(m is not None and not m for m in covered.values()):
        raise SystemExit(f"no wheels for every platform: {wheels[:3]} ...")
    return min(limits) if limits else None


def requires_max(spec: str | None) -> int | None:
    """Upper bound of Requires-Python, e.g. "<3.16,>=3.10" -> 15."""
    tops = [int(m.group(2)) - (m.group(1) == "<")
            for m in re.finditer(r"(<=?)\s*3\.(\d+)", spec or "")]
    return min(tops) if tops else None


def main() -> int:
    lines, cap = [], None
    for name, version in resolve():
        data = pypi(name, version)
        files = [f for f in data["urls"] if f["packagetype"] == "bdist_wheel"]
        if not files:
            raise SystemExit(f"{name} {version}: no wheels on PyPI")
        tops = [t for t in (max_series([f["filename"] for f in files]),
                            requires_max(data["info"].get("requires_python"))) if t is not None]
        top = min(tops) if tops else None
        if top is not None:
            cap = top if cap is None else min(cap, top)
        hashes = sorted({f["digests"]["sha256"] for f in files})
        lines.append(f"{name}=={version} \\\n" + " \\\n".join(f"    --hash=sha256:{h}" for h in hashes))
        print(f"{name}=={version}: {len(hashes)} wheels" + (f", up to Python 3.{top}" if top else ""))
    header = ("# Generated by tools/lock_deps.py from requirements.in - do not edit by hand.\n"
              "# Installed with pip --require-hashes: exact versions, every file checked against its SHA-256.\n"
              f"# python-max: 3.{cap if cap is not None else 99}\n")
    OUT.write_text(header + "\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"Wrote {OUT.name}; newest supported Python: 3.{cap}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
